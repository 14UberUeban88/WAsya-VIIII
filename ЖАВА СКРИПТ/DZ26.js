function solveEquation(a, b, c) {
  // Считаем дискриминант
  const d = b * b - 4 * a * c;

  // Если дискриминант меньше нуля — возвращаем пустой массив []
  if (d < 0) {
    return [];
  }

  // Если дискриминант равен нулю — возвращаем число 1 (количество корней)
  if (d === 0) {
    return 1;
  }

  // Если дискриминант больше нуля — возвращаем массив с двумя корнями
  const x1 = (-b + Math.sqrt(d)) / (2 * a);
  const x2 = (-b - Math.sqrt(d)) / (2 * a);
  return [x1, x2];
}

// === Проверка (выведет в консоль точно так, как вам нужно) ===

// 1. Для уравнения с одним корнем (например, x² - 6x + 9 = 0)
console.log(solveEquation(1, -6, 9)); // Выведет: 1

// 2. Для уравнения без корней (например, x² + 2x + 5 = 0)
console.log(solveEquation(1, 2, 5));  // Выведет: []

// 3. Для уравнения с двумя корнями (например, x² - 5x + 6 = 0)
console.log(solveEquation(1, -5, 6)); // Выведет: [ 3, 2 ]
