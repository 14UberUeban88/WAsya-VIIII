// Переменная для хранения общего количества символов
let totalCharacters = 0;

while (true) {
  // Запрашиваем строку у пользователя
  let userInput = prompt("Введите строку:");

  // Проверяем, если пользователь нажал "Отмена" (null) или ввел пустую строку
  if (userInput === null) {
    break; // Выходим из цикла, если ввод отменен
  }

  // Убираем лишние пробелы по краям и переводим в нижний регистр для проверки на "стоп"
  let cleanedInput = userInput.trim().toLowerCase();

  // Проверяем условие остановки
  if (cleanedInput === "стоп") {
    break; // Завершаем выполнение цикла
  }

  // Считаем символы в текущей строке, удаляя ВСЕ пробелы внутри нее
  // Используем регулярное выражение / /g для замены всех пробелов на пустую строку
  let stringWithoutSpaces = userInput.replace(/ /g, "");
  
  // Прибавляем длину очищенной строки к общему счетчику
  totalCharacters += stringWithoutSpaces.length;
}

// Выводим итоговый результат в консоль
console.log("Количество символов (без пробелов): " + totalCharacters);
