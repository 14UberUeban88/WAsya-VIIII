"use strict";
// 2. Реализация функции (общая логика для всех вариантов)
function formatTasks(tasks, category) {
    // Объединяем массив строк в одну строку через запятую и пробел
    const joinedTasks = tasks.join(", ");
    // Если передана категория, добавляем её как заголовок
    if (category) {
        return `[${category}] ${joinedTasks}`;
    }
    // Если категории нет, возвращаем только объединенные задачи
    return joinedTasks;
}
// === ДЕМОНСТРАЦИЯ И ПРОВЕРКА РАБОТЫ ===
const myTasks = ["Купить молоко", "Сделать домашку", "Полить цветы"];
// Вариант 1: Вызов только со списком задач
const result1 = formatTasks(myTasks);
console.log(`Задачи: ${result1}`);
// Выведет: Задачи: Купить молоко, Сделать домашку, Полить цветы
// Вариант 2: Вызов со списком задач и категорией
const result2 = formatTasks(myTasks, "Важное");
console.log(`Задачи: ${result2}`);
// Выведет: Задачи: [Важное] Купить молоко, Сделать домашку, Полить цветы
