// Функция для проверки настроения, принимающая строку и callback-функцию
function askMood(mood, callback) {
  // Вызываем callback-функцию и передаем в неё настроение
  callback(mood);
}

// Callback-функция, которая анализирует настроение и выводит совет
function suggestActivity(userMood) {
  // Приводим к нижнему регистру и убираем пробелы, чтобы избежать ошибок при вводе
  // Если пользователь нажал Отмена в prompt, запишем пустую строку
  let cleanMood = userMood ? userMood.trim().toLowerCase() : "";

  // Проверяем настроение и выводим нужную рекомендацию
  if (cleanMood === "весёлое" || cleanMood === "веселое") {
    console.log("Послушай музыку или позвони другу!");
  } else if (cleanMood === "грустное") {
    console.log("Соверши небольшую прогулку или посмотри комедию");
  } else if (cleanMood === "подавленное") {
    console.log("Отдохни! Можно просто поспать или принять ванну");
  } else {
    console.log("Сделай что-то приятное для себя.");
  }
}

// --- Основная часть программы ---

// Запрашиваем настроение у пользователя
let currentMood = prompt("Введите ваше настроение:");

// Вызываем главную функцию, передавая в неё ввод и нашу callback-функцию
askMood(currentMood, suggestActivity);
