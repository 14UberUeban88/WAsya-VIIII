// 1. Создаем функцию loadData, которая возвращает новый промис
function loadData() {
    return new Promise((resolve, reject) => {
        // 2. Используем setTimeout с задержкой в 1500 мс
        setTimeout(() => {
            // 3. Генерируем случайное число для вероятности 50% на 50%
            let isSuccess = Math.random() < 0.5;

            if (isSuccess) {
                // Если успешно, возвращаем объект с «данными с сервера»
                resolve({ status: "success", data: "Данные успешно загружены!" });
            } else {
                // Если ошибка, отклоняем промис с текстом ошибки
                reject("Ошибка соединения: Сервер не отвечает");
            }
        }, 1500); // Задержка ровно полторы секунды
    });
}

// 4. Вызываем функцию и обрабатываем результат с помощью .then() и .catch()
loadData()
    .then((response) => {
        // Сюда мы попадаем асинхронно, если всё загрузилось отлично
        console.log(`Успех! Сообщение от сервера: ${response.data}`);
    })
    .catch((serverError) => {
        // Сюда мы перелетаем, если сработали те самые 50% с ошибкой
        console.log(`Произошла ошибка: ${serverError}`);
    });
