const userName = prompt("Введите ваше имя:");
const ageInput = prompt("Введите ваш возраст:");

// Преобразуем строковое значение в число
const userAge = +ageInput; 

// Проверяем корректность ввода (на буквы, пустую строку или отрицательное число)
if (Number.isNaN(userAge) || ageInput.trim() === "" || userAge < 0) {
    alert("Ошибка: Пожалуйста, введите корректное число для возраста.");
} else {
    // Выводим приветственное сообщение
    alert(`Привет, ${userName}! Тебе ${userAge} лет.`);
}
